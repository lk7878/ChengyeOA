import test from 'node:test';
import assert from 'node:assert/strict';
import mm from 'egg-mock';
import { PrismaClient } from '@prisma/client';
import { createApiSession } from '../helpers/auth-session';
import { createTestPrisma, clearTestApplicationData } from '../helpers/test-database';
process.env.EGG_TYPESCRIPT = 'true';
const app = mm.app(); let db: PrismaClient;
test.before(async () => { db = createTestPrisma(); await app.ready(); await clearTestApplicationData(db); });
test.after(async () => { await clearTestApplicationData(db); await db.$disconnect(); await app.close(); await mm.restore(); });
test('inventory API enforces authentication and grants, serializes decimals and persists a complete stock cycle', async () => {
  await app.httpRequest().get('/api/v1/inventory').expect(401);
  const user = await db.user.create({ data: { username: 'inventory-admin', password: 'test' } });
  const role = await db.role.create({ data: { code: 'SYSTEM_SUPER_ADMIN', name: '超级管理员', type: 'SYSTEM', status: 'ENABLED' } });
  await db.userRole.create({ data: { userId: user.id, roleId: role.id } });
  const token = (await createApiSession(db, user.id, 'MFA')).token;
  const headers = { Authorization: 'Bearer ' + token };
  const ordinary = await db.user.create({ data: { username: 'ordinary', password: 'test' } });
  const denied = { Authorization: 'Bearer ' + (await createApiSession(db, ordinary.id, 'PASSWORD')).token };
  await app.httpRequest().get('/api/v1/inventory').set(denied).expect(403);
  await app.httpRequest().post('/api/v1/inventory/movements').set(denied).send({ action: 'INBOUND' }).expect(403);
  const created = await app.httpRequest().post('/api/v1/inventory/items').set(headers).send({ name: '定制笔记本', kind: 'CUSTOMIZED', category: '文具', unit: '本' }).expect(200);
  const item = created.body.data; assert.equal(item.stock, '0');
  await app.httpRequest().post('/api/v1/inventory/movements').set(headers).send({ itemId: item.id, version: item.version, action: 'INBOUND', quantity: '10', occurredAt: '2026-09-11', idempotencyKey: 'api-inbound' }).expect(200);
  await app.httpRequest().post('/api/v1/inventory/stocktakes').set(headers).send({ itemId: item.id, version: 2, actualStock: '9', reason: '盘点核实', occurredAt: '2026-09-11', idempotencyKey: 'api-stocktake' }).expect(200);
  const listed = await app.httpRequest().get('/api/v1/inventory?view=items&kind=CUSTOMIZED').set(headers).expect(200);
  assert.equal(listed.body.data.list[0].stock, '9');
  const exported = await app.httpRequest().get('/api/v1/inventory/export?view=stocktakes').set(headers).expect(200);
  assert.match(exported.body.data.csv, /实盘数量/); assert.match(exported.body.data.csv, /盘点核实/);
});
