import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import test from 'node:test';

import { PermanentEventError, RetryableEventError } from '../../app/domain/events/event-errors';
import { allowedSubscriptionFields, parseEventPayload, validateEventEnvelope } from '../../app/domain/events/event-registry';
import { retryDecision } from '../../app/domain/events/retry-policy';
import { matchesSubscriptionFilter, parseSubscriptionFilter } from '../../app/domain/events/subscription-filter';

const operationId = '11111111-1111-4111-8111-111111111111';
const requesterUserId = '22222222-2222-4222-8222-222222222222';

function validPayload(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    operationId,
    operationType: 'SYSTEM_ADMIN_GRANT',
    riskLevel: 'HIGH',
    decision: 'APPROVE',
    status: 'APPROVED',
    requesterUserId,
    routeUrl: `/security/admin-governance?operationId=${operationId}`,
    ...overrides,
  };
}

test('accepts the exact reviewed-v1 payload and derives a stable ordering key', () => {
  const parsed = parseEventPayload('admin.operation.reviewed', 1, validPayload());

  assert.equal(parsed.sourceModule, 'ADMIN_GOVERNANCE');
  assert.equal(parsed.objectType, 'ADMIN_OPERATION');
  assert.equal(parsed.objectId, operationId);
  assert.equal(
    parsed.orderingKey,
    createHash('sha256').update(`ADMIN_OPERATION:${operationId}`, 'utf8').digest('hex'),
  );
  assert.match(parsed.orderingKey, /^[a-f0-9]{64}$/);
});

test('preserves the registered post-review CONFIRM decision', () => {
  const parsed = parseEventPayload('admin.operation.reviewed', 1, validPayload({
    decision: 'CONFIRM',
    status: 'CONFIRMED',
  }));

  assert.equal(parsed.payload.decision, 'CONFIRM');
  assert.equal(parsed.payload.status, 'CONFIRMED');
});

test('rejects payloads that do not have exactly the registered fields', () => {
  assert.throws(() => parseEventPayload('admin.operation.reviewed', 1, validPayload({ unexpected: true })));
});

for (const forbidden of [
  'password', 'secret', 'token', 'authorization', 'cookie', 'csrf', 'totp', 'mfa',
  'recoveryCode', 'credential', 'encryptedSecret', 'reason', 'comment', 'oldValues', 'newValues',
]) {
  test(`rejects recursively forbidden field ${forbidden}`, () => {
    assert.throws(
      () => parseEventPayload(
        'admin.operation.reviewed',
        1,
        validPayload({ nested: { [forbidden]: 'x' } }),
      ),
      (error: unknown) => error instanceof TypeError && error.message.includes(`forbidden field ${forbidden}`),
    );
  });
}

test('rejects a route URL that was not generated by the server for the operation', () => {
  assert.throws(() => parseEventPayload(
    'admin.operation.reviewed',
    1,
    validPayload({ routeUrl: 'https://attacker.invalid/security/admin-governance' }),
  ));
});

test('rejects unsafe JSON values before registering an event payload', () => {
  assert.throws(() => parseEventPayload(
    'admin.operation.reviewed',
    1,
    validPayload({ operationId: Number.NaN }),
  ));
  assert.throws(() => parseEventPayload(
    'admin.operation.reviewed',
    1,
    Object.assign(Object.create(null), validPayload()),
  ));
});

test('validates the registered event envelope and derives registry-owned fields', () => {
  const event = validateEventEnvelope({
    eventType: 'admin.operation.reviewed',
    eventVersion: 1,
    objectType: 'ADMIN_OPERATION',
    objectId: operationId,
    operatorUserId: requesterUserId,
    organizationId: null,
    branchId: null,
    teamId: null,
    payload: validPayload(),
    traceId: 'request-11111111-1111-4111-8111-111111111111',
    occurredAt: new Date('2026-07-22T00:00:00.000Z'),
  });

  assert.equal(event.sourceModule, 'ADMIN_GOVERNANCE');
  assert.equal(event.orderingKey, createHash('sha256').update(`ADMIN_OPERATION:${operationId}`, 'utf8').digest('hex'));
});

test('accepts only registered filter fields and matches EQ and IN clauses', () => {
  const filter = parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [
      { field: 'riskLevel', operator: 'EQ', values: [ 'HIGH' ] },
      { field: 'decision', operator: 'IN', values: [ 'APPROVE', 'FLAG' ] },
    ],
  });

  assert.equal(matchesSubscriptionFilter(filter, validPayload()), true);
  assert.equal(matchesSubscriptionFilter(filter, validPayload({ riskLevel: 'LOW' })), false);
  assert.throws(() => parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'nested.value', operator: 'EQ', values: [ 'x' ] } ],
  }));
});

test('enforces filter clause, value, and string-length limits', () => {
  assert.throws(() => parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: Array.from({ length: 11 }, () => ({ field: 'riskLevel', operator: 'EQ', values: [ 'HIGH' ] })),
  }));
  assert.throws(() => parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'riskLevel', operator: 'IN', values: Array.from({ length: 21 }, () => 'HIGH') } ],
  }));
  assert.throws(() => parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'riskLevel', operator: 'EQ', values: [ 'x'.repeat(101) ] } ],
  }));
});

test('does not permit callers to mutate the registered filter whitelist', () => {
  const fields = allowedSubscriptionFields('admin.operation.reviewed', 1);
  (fields as Set<string>).add('routeUrl');

  assert.throws(() => parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'routeUrl', operator: 'EQ', values: [ 'not-a-filterable-route' ] } ],
  }));
});

test('accepts filters at the exact clause, IN-value, and string-length limits', () => {
  const tenClauses = parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: Array.from({ length: 10 }, () => ({ field: 'riskLevel', operator: 'EQ', values: [ 'HIGH' ] })),
  });
  const twentyValues = parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'riskLevel', operator: 'IN', values: Array.from({ length: 20 }, () => 'HIGH') } ],
  });
  const oneHundredCharacters = parseSubscriptionFilter('admin.operation.reviewed', 1, {
    all: [ { field: 'requesterUserId', operator: 'EQ', values: [ 'x'.repeat(100) ] } ],
  });

  assert.equal(tenClauses.all.length, 10);
  assert.equal(twentyValues.all[0].values.length, 20);
  assert.equal(oneHundredCharacters.all[0].values[0], 'x'.repeat(100));
});

test('uses the fixed retry schedule and sends attempt five to MANUAL', () => {
  assert.deepEqual([ 1, 2, 3, 4, 5 ].map(attempt => retryDecision(attempt)), [
    { kind: 'RETRY_WAIT', delayMs: 15_000 },
    { kind: 'RETRY_WAIT', delayMs: 300_000 },
    { kind: 'RETRY_WAIT', delayMs: 3_600_000 },
    { kind: 'RETRY_WAIT', delayMs: 21_600_000 },
    { kind: 'MANUAL' },
  ]);
});

test('marks event handler errors with stable error codes', () => {
  assert.equal(new RetryableEventError('TRANSIENT_FAILURE').code, 'TRANSIENT_FAILURE');
  assert.equal(new PermanentEventError('SOURCE_INVALID').code, 'SOURCE_INVALID');
});
