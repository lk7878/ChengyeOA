// SPEC-013 Task 4: 审批中心域稳定错误码与错误载体。
// 形态逐字仿 domain/finance/finance-errors.ts：个体常量 + 联合类型 + 聚合对象 + HTTP 表 + Error 子类。
// 8 码：404×3（DEFINITION/INSTANCE/TASK_NOT_FOUND）、409×3（STATE_INVALID/SELF_REVIEW_FORBIDDEN/CALLBACK_KEY_CONFLICT）、400×2（ASSIGNEE_INVALID/DEFINITION_CODE_CONFLICT）。
// SPEC-017 Task 1: +APPROVAL_DEFINITION_CODE_CONFLICT（400，create code 唯一冲突）。

export const APPROVAL_DEFINITION_NOT_FOUND = 'APPROVAL_DEFINITION_NOT_FOUND';
export const APPROVAL_INSTANCE_NOT_FOUND = 'APPROVAL_INSTANCE_NOT_FOUND';
export const APPROVAL_TASK_NOT_FOUND = 'APPROVAL_TASK_NOT_FOUND';
export const APPROVAL_STATE_INVALID = 'APPROVAL_STATE_INVALID';
export const APPROVAL_SELF_REVIEW_FORBIDDEN = 'APPROVAL_SELF_REVIEW_FORBIDDEN';
export const APPROVAL_ASSIGNEE_INVALID = 'APPROVAL_ASSIGNEE_INVALID';
export const CALLBACK_KEY_CONFLICT = 'CALLBACK_KEY_CONFLICT';
export const APPROVAL_DEFINITION_CODE_CONFLICT = 'APPROVAL_DEFINITION_CODE_CONFLICT';

export type ApprovalErrorCode =
  | typeof APPROVAL_DEFINITION_NOT_FOUND
  | typeof APPROVAL_INSTANCE_NOT_FOUND
  | typeof APPROVAL_TASK_NOT_FOUND
  | typeof APPROVAL_STATE_INVALID
  | typeof APPROVAL_SELF_REVIEW_FORBIDDEN
  | typeof APPROVAL_ASSIGNEE_INVALID
  | typeof CALLBACK_KEY_CONFLICT
  | typeof APPROVAL_DEFINITION_CODE_CONFLICT;

/** 聚合对象形态：供 service 层（Task 5）以 APPROVAL_ERROR_CODES.X 引用，值与个体常量同一引用。 */
export const APPROVAL_ERROR_CODES = {
  APPROVAL_DEFINITION_NOT_FOUND,
  APPROVAL_INSTANCE_NOT_FOUND,
  APPROVAL_TASK_NOT_FOUND,
  APPROVAL_STATE_INVALID,
  APPROVAL_SELF_REVIEW_FORBIDDEN,
  APPROVAL_ASSIGNEE_INVALID,
  CALLBACK_KEY_CONFLICT,
  APPROVAL_DEFINITION_CODE_CONFLICT,
} as const;

/** 每个稳定码钉死的默认 HTTP 状态码；冲突类（409）与校验类（400）语义由抛出方场景决定。 */
export const APPROVAL_ERROR_HTTP_STATUS: Readonly<Record<ApprovalErrorCode, number>> = {
  [APPROVAL_DEFINITION_NOT_FOUND]: 404,
  [APPROVAL_INSTANCE_NOT_FOUND]: 404,
  [APPROVAL_TASK_NOT_FOUND]: 404,
  [APPROVAL_STATE_INVALID]: 409,
  [APPROVAL_SELF_REVIEW_FORBIDDEN]: 409,
  [APPROVAL_ASSIGNEE_INVALID]: 400,
  [CALLBACK_KEY_CONFLICT]: 409,
  [APPROVAL_DEFINITION_CODE_CONFLICT]: 400,
};

export class ApprovalError extends Error {
  constructor(
    public readonly code: ApprovalErrorCode,
    public readonly httpStatus: number,
    message: string,
  ) {
    super(message);
    this.name = 'ApprovalError';
  }
}
