function permission(
  code: PermissionCode,
  name: string,
  type: PermissionType,
  resource: ResourceCode,
  action: string,
  riskLevel: RiskLevel,
  route: string | null = null,
): PermissionCatalogEntry {
  return Object.freeze({
    id: `permission:${code}`,
    code,
    name,
    type,
    resource,
    action,
    riskLevel,
    status: 'ENABLED',
    route,
  });
}

