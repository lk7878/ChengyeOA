import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { InventoryItem, InventoryRow } from '../src/api/inventory';
test.use({ channel: 'msedge', viewport: { width: 1600, height: 1100 } });
test('Chinese inventory forms register stock, preserve failed input, take stock and export', async ({ page }) => {
  test.setTimeout(60000);
  let item: InventoryItem | undefined;
  const movements: InventoryRow[] = [], takes: InventoryRow[] = [];
  const person = { id: 'employee-1', name: '张三', employeeNo: '001', organizationPath: '重庆承业律师事务所/律师部' };
  await page.route('**/api/v1/**', async route => {
    const req=route.request(), url=new URL(req.url()), path=url.pathname;
    const ok=(data:unknown)=>route.fulfill({json:{code:200,message:'success',data}});
    const error=(message:string)=>route.fulfill({status:409,json:{code:409,message}});
    if(path.endsWith('/recipients'))return ok([person]);
    if(path.endsWith('/export'))return ok({fileName:'物品管理台账.csv',csv:'物品名称,领用数量,单位\r\n中性笔,3,支'});
    if(req.method()==='POST' && path.endsWith('/items')){const data=req.postDataJSON();item={...data,id:'item-1',code:'WP-001',stock:'0',version:1};return ok(item);}
    if(req.method()==='POST'){
      const data=req.postDataJSON();expect(data.itemId).toBe(item!.id);expect(data.version).toBe(item!.version);expect(data.idempotencyKey).toBeTruthy();
      const stock=Number(item!.stock), isTake=path.endsWith('/stocktakes');
      const delta=isTake?Number(data.actualStock)-stock:data.action==='OUTBOUND'?-Number(data.quantity):Number(data.quantity);
      if(stock+delta<0)return error('INVENTORY_INSUFFICIENT');
      if(isTake && delta!==0 && !data.reason)return error('INVENTORY_REASON_REQUIRED');
      const row={...data,id:'record-'+(movements.length+takes.length),documentNo:'NO-'+(movements.length+takes.length),itemName:item!.name,unit:item!.unit,quantity:String(delta),beforeStock:String(stock),afterStock:String(stock+delta),bookStock:String(stock),actualStock:String(stock+delta),difference:String(delta),employeeName:person.name,organizationPath:person.organizationPath,createdByName:'测试管理员'};
      item!.stock=String(stock+delta);item!.version++;if(isTake)takes.push(row);else movements.push(row);return ok(row);
    }
    const view=url.searchParams.get('view');
    const stats=movements.filter(r=>r.action==='OUTBOUND').map(r=>({...r,quantity:String(-Number(r.quantity)),count:1}));
    if(view==='dashboard')return ok({itemCount:item?1:0,lowStockCount:0,inboundCount:1,outboundCount:1,top:stats});
    const list=view==='items'?(item?[item]:[]):view==='stocktakes'?takes:view==='statistics'?stats:movements.filter(r=>!url.searchParams.get('action')||r.action===url.searchParams.get('action'));
    return ok({list,total:list.length});
  });
  await page.goto('http://localhost:3000/e2e/inventory.html');
  await page.getByRole('button',{name:'新增物品',exact:true}).click();
  await page.getByRole('textbox',{name:'物品名称',exact:true}).fill('中性笔');
  await page.getByRole('textbox',{name:'中文分类',exact:true}).fill('书写用品');
  await page.getByRole('textbox',{name:'计量单位',exact:true}).fill('支');
  await page.getByRole('button',{name:/保.*存/,exact:true}).click();
  const row=page.getByRole('row').filter({has:page.getByRole('cell',{name:'中性笔',exact:true})});
  await row.getByRole('button',{name:'入库',exact:true}).click();
  await page.getByRole('spinbutton',{name:'数量',exact:true}).fill('10');
  await page.getByRole('button',{name:'确认登记',exact:true}).click();
  await expect(row.getByRole('cell',{name:'10',exact:true})).toBeVisible();
  await row.getByRole('button',{name:'领用',exact:true}).click();
  await page.getByRole('spinbutton',{name:'数量',exact:true}).fill('3');
  await page.getByRole('combobox',{name:'领用人',exact:true}).click();
  await page.getByText('张三（001） / 重庆承业律师事务所/律师部',{exact:true}).click();
  await page.getByRole('textbox',{name:'用途或原因',exact:true}).fill('日常办公');
  await page.getByRole('button',{name:'确认登记',exact:true}).click();
  await expect(row.getByRole('cell',{name:'7',exact:true})).toBeVisible();
  await row.getByRole('button',{name:'领用',exact:true}).click();
  await page.getByRole('spinbutton',{name:'数量',exact:true}).fill('8');
  await page.getByRole('combobox',{name:'领用人',exact:true}).click();await page.getByText('张三（001） / 重庆承业律师事务所/律师部',{exact:true}).click();
  await page.getByRole('textbox',{name:'用途或原因',exact:true}).fill('会议用品');await page.getByRole('button',{name:'确认登记',exact:true}).click();
  await expect(page.getByText('库存不足，无法领用该数量；当前输入已保留',{exact:true})).toBeVisible();
  await expect(page.getByRole('spinbutton',{name:'数量',exact:true})).toHaveValue('8.000');expect(item!.stock).toBe('7');
  await page.getByRole('button',{name:/取.*消/,exact:true}).click();
  await row.getByRole('button',{name:'盘点',exact:true}).click();
  await page.getByRole('spinbutton',{name:'实盘数量',exact:true}).fill('6');
  await page.getByRole('button',{name:'确认登记',exact:true}).click();await expect(page.getByText('请填写领用用途或盘点差异原因',{exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'用途或原因',exact:true}).fill('损耗核实');await page.getByRole('button',{name:'确认登记',exact:true}).click();
  await expect(row.getByRole('cell',{name:'6',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'领用明细',exact:true}).click();await expect(page.getByRole('cell',{name:person.organizationPath,exact:true})).toBeVisible();
  await page.getByRole('link',{name:'盘点记录',exact:true}).click();await expect(page.getByRole('cell',{name:'损耗核实',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'领用统计',exact:true}).click();await expect(page.getByRole('cell',{name:'3',exact:true})).toBeVisible();
  const downloading=page.waitForEvent('download');await page.getByRole('button',{name:'导出当前筛选',exact:true}).click();const download=await downloading;
  expect(await readFile((await download.path())!,'utf8')).toContain('中性笔,3,支');
  await page.getByRole('link',{name:'仪表盘',exact:true}).click();await expect(page.getByText('期间领用笔数',{exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath('inventory-dashboard.png'),fullPage:true});
});
