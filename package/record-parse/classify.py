def _compact(text):
    return "".join((text or "").split())


def alias_to_category(label):
    if not label:
        return None
    compact = _compact(label)
    for alias, cat in TYPE_ALIASES:
        if alias in label or _compact(alias) in compact:
            return cat
    return None


def try_confident_category(content, hint=""):
    cat = decide_category(content, hint)
    if cat and cat != "其他":
        return cat
    return None


def decide_category(content, hint=""):
    header = (content or "")[:900]
    t = hint or ""
    if any(k in t or k in header for k in ("抢救记录", "抢救处置", "心肺复苏记录")):
        return "抢救记录"
    if any(k in header for k in ("CPR", "心肺复苏", "胸外按压")) and any(
        k in header for k in ("除颤", "肾上腺素", "气管插管", "抢救")
    ):
        return "抢救记录"
    if "产前超声" in header or "胎儿超声" in header:
        return "影像报告"
    if "NIPT" in header or "无创DNA" in header or "唐氏筛查" in header:
        return "检验报告"

    aliased = alias_to_category(t) or alias_to_category(header)
    if aliased:
        return aliased
    if t in DOC_CATEGORIES:
        return t
    compact = _compact(header)
    for cat, keywords in HEADER_KEYWORDS:
        if any(kw in header or _compact(kw) in compact for kw in keywords):
            return cat
    return "其他"


def specific_type(content, category):
    header = _compact((content or "")[:400])
    for alias, cat in TYPE_ALIASES:
        if cat == category and _compact(alias) in header:
            return alias
    return category
